package biz.lobachev.annette.data_dictionary.generators.click_house_ddl

import biz.lobachev.annette.data_dictionary.model.*
import biz.lobachev.annette.data_dictionary.utils.StringSyntax.*
import biz.lobachev.annette.data_dictionary.generators.{GeneratedFile, TextGenerator}
import biz.lobachev.annette.data_dictionary.labels.ClickHouse

import java.time.OffsetDateTime
import java.time.format.DateTimeFormatter

case class ClickHouseDDLGenerator(
  domain: Domain,
  filename: String = "click_house_ddl.sql",
) extends TextGenerator
    with DomainMetaHelper {

  private def header() = {
    val formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")
    val date      = OffsetDateTime.now().toLocalDateTime.format(formatter)
    Seq(
      s"-- ${domain.name}",
      "-- Code generated by Data Dictionary Builder (c) Valery Lobachev (https://github.com/valerylobachev/data-dictionary-builder).",
      s"-- Date: $date",
      "",
    ).mkString("\n")
  }

  override def generate(): Seq[GeneratedFile] = {
    val content = header() + generateSchemas() + generateTables()
    Seq(
      Some(
        GeneratedFile(
          path = "",
          filename = filename,
          content = content,
        ),
      ),
    ).flatten
  }

  private def generateSchemas(): String = {
    val schemas = domain.tables.values.flatMap { table =>
      val exclude = getTableLabel(table, ClickHouse.CLICKHOUSE_ENGINE_EXCLUDE, domain)
      if exclude.isDefined then None
      else getFullTableName(table, domain).schema
    }.toSet
    schemas.map { schema =>
      val schemaName = wrapQuotes(schema)
      s"CREATE SCHEMA $schemaName;\n"
    }
  }.mkString("\n", "\n", "")

  private def generateTables(): String =
    domain.tables.values
      .map(t => generateTable(t))
      .flatten
      .mkString("\n", "\n", "")

  private def generateTable(table: Table): Option[String] =
    if (
      table.labels
        .get(ClickHouse.CLICKHOUSE_ENGINE)
        .map(e => e != ClickHouse.CLICKHOUSE_ENGINE_EXCLUDE)
        .getOrElse(true)
    ) {
      val fields = table.fields.map { field =>
        val fieldName = wrapQuotes(field.dbFieldName)
        val datatype  = getClickHouseDatatype(field.datatype, domain).datatype
        val notNull   = if (field.notNull) " NOT NULL" else ""
        val comment   = if (!field.name.trim.isBlank()) {
          s" COMMENT '${field.name}'"
        } else ""
        s"  $fieldName $datatype$notNull$comment"
      }.mkString(",\n")

      val primaryKey = if (table.pk.nonEmpty) {
        val pkFields = table.pk.map(f => getEntityFieldName(table.fields, f)).mkString("(", ", ", ")")
        s"\n  PRIMARY KEY $pkFields"
      } else ""

      val tableComment = if (!table.name.trim.isBlank()) {
        s"\n  COMMENT '${table.name}'"
      } else ""

      val engine = table.labels.get(ClickHouse.CLICKHOUSE_ENGINE).getOrElse("MergeTree()")

      val fullTableName = getFullTableName(table, domain)

      val tableDdl = Seq(
        s"CREATE TABLE ${fullTableName.toDbName} (",
        fields,
        ")\n" +
          s"  ENGINE = $engine" +
          s"$primaryKey$tableComment;\n",
      ).mkString("\n")

      Some(tableDdl)
    } else None

  def getEntityFieldName(field: Seq[TableField], fieldName: String): String =
    field
      .find(f => f.fieldName == fieldName)
      .map(f => wrapQuotes(f.dbFieldName))
      .getOrElse {
        throw new IllegalArgumentException(s"not found field $fieldName")
      }

}
