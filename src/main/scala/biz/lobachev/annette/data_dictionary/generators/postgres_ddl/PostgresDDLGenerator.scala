package biz.lobachev.annette.data_dictionary.generators.postgres_ddl

import biz.lobachev.annette.data_dictionary.generators.{GeneratedFile, TextGenerator}
import biz.lobachev.annette.data_dictionary.model.*
import biz.lobachev.annette.data_dictionary.utils.StringSyntax.*

import java.time.OffsetDateTime
import java.time.format.DateTimeFormatter

case class PostgresDDLGenerator(
  domain: Domain,
  filename: String = "postgres_ddl.sql",
  withNameComment: Boolean = false,
  withDescriptionComment: Boolean = false,
) extends TextGenerator
    with DomainMetaHelper {

  override def generate(): Seq[GeneratedFile] = {
    val content = header() +
      generateEnums() +
      generateSchemas() +
      generateTables() +
      generateIndexes() +
      generateComments() +
      generateRelations()

    Seq(
      GeneratedFile(
        s"",
        filename,
        content,
      ),
    )
  }

  private def header() = {
    val formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")
    val date      = OffsetDateTime.now().toLocalDateTime.format(formatter)
    Seq(
      s"-- ${domain.name}",
      "-- Code generated by Data Dictionary Builder (c) Valery Lobachev (https://github.com/valerylobachev/data-dictionary-builder).",
      s"-- Date: $date",
      "",
    ).mkString("\n")
  }

  private def generateEnums(): String =
    domain.enums.values
      .filter(_.enumType == NativeEnum)
      .map { e =>
        val enumId = e.id.snakeCase
        s"CREATE TYPE $enumId AS ENUM (\n" +
          e.elements.map { el =>
            val comma = if el.id == e.elements.last._1 then " " else ","
            s"  '${el.id}'$comma -- ${el.name} \n"
          }.mkString("") +
          ");\n"
      }
      .mkString("\n", "\n", "")

  private def generateSchemas(): String = {
    val schemas = domain.tables.values.flatMap { table =>
      getFullTableName(table, domain).schema
    }.toSet
    schemas.map { schema =>
      val schemaName = wrapQuotes(schema)
      s"CREATE SCHEMA $schemaName;\n"
    }
  }.mkString("\n", "\n", "")

  private def generateTables(): String =
    domain.tables.values.map { table =>

      val fields = table.fields.map { field =>
        val fieldName             = wrapQuotes(field.dbFieldName)
        val datatype              = getPostgresTableFieldDatatype(field, domain).datatype
        val primaryKey            = if (table.pk.length == 1 && table.pk.head == field.fieldName) " PRIMARY KEY" else ""
        val notNull               = if (field.notNull) " NOT NULL" else ""
        val checkEnum             = getEnumData(field.datatype, domain).flatMap { ed =>
          if ed.enumType != NativeEnum && ed.strict && ed.elements.nonEmpty then {
            val list = ed.elements.map(e => s"'${e.id}'").mkString(", ")
            Some(s" check  ($fieldName in ($list))")
          } else None
        }
          .getOrElse("")
        val default               = field.default.map {
          case DefaultValue(value)         => s" DEFAULT '$value'"
          case DefaultStatement(statement) => s" DEFAULT $statement"
        }.getOrElse("")
        val generated             = field.generated.map {
          case GeneratedAlwaysAsIdentity             => " GENERATED ALWAYS AS IDENTITY"
          case GeneratedByDefaultAsIdentity          => " GENERATED BY DEFAULT AS IDENTITY"
          case GeneratedAlwaysAs(statement, Stored)  =>
            s" GENERATED ALWAYS AS( $statement ) STORED"
          case GeneratedAlwaysAs(statement, Virtual) =>
            s" GENERATED ALWAYS AS( $statement ) VIRTUAL"
        }.getOrElse("")
        val descriptionCommentSeq = getDescriptionComments(field.description)
        val descriptionComments   =
          if descriptionCommentSeq.isEmpty then ""
          else descriptionCommentSeq.map("  " + _).mkString("", "\n", "\n")
        val comma                 = if table.fields.last != field || table.pk.length > 1 then "," else ""
        val nameComment           = getNameComment(field.name).map(" " + _).getOrElse("")

        s"$descriptionComments  $fieldName $datatype$primaryKey$notNull$checkEnum$default$generated$comma$nameComment"

      }.mkString("\n")

      val fullTableName = getFullTableName(table, domain).toDbName

      val primaryKey = if (table.pk.length > 1) {
        val pkFields = table.pk.map(f => getTableDbFieldName(table.fields, f)).mkString("(", ", ", ")")
        s"\n  PRIMARY KEY $pkFields"
      } else ""

      val tableComments = getNameComment(table.name).toSeq ++ getDescriptionComments(table.description)

      (
        tableComments ++
          Seq(
            s"CREATE TABLE $fullTableName (",
            fields + primaryKey,
            ");\n",
          )
      ).mkString("\n")

    }
      .mkString("\n", "\n", "")

  private def generateIndexes(): String =
    domain.tables.values.flatMap { table =>
      val fullTableName = getFullTableName(table, domain).toDbName
      table.indexes.map { index =>
        val unique      = if (index.unique) "UNIQUE " else ""
        val indexId     = wrapQuotes(getTableIndexConstraintName(table.tableName, index.id.snakeCase))
        val fields      = index.fields.map { f =>
          val dbFieldName = getTableDbFieldName(table.fields, f.fieldName)
          val indexNulls  = f.indexNulls match {
            case Some(NullsFirst) => " NULLS FIRST"
            case Some(NullsLast)  => " NULLS LAST"
            case None             => ""
          }
          val desc        = if f.descending then " DESC" else ""
          s"$dbFieldName$desc$indexNulls"
        }.mkString("(", ", ", ")")
        val usingMethod = index.method.map(m => s"USING ${m.method} ").getOrElse("")
        val include     = if (index.includeFields.nonEmpty) {
          val includeFields =
            index.includeFields.map(f => getTableDbFieldName(table.fields, f)).mkString("(", ", ", ")")
          s" INCLUDE $includeFields "
        } else ""
        val where       = index.condition.map(c => s" WHERE $c").getOrElse("")
        s"CREATE ${unique}INDEX $indexId ON $fullTableName $usingMethod$fields$include$where;\n"
      }
    }.mkString("\n", "\n", "")

  private def generateComments(): String =
    domain.tables.values.flatMap { table =>
      val fullTableName = getFullTableName(table, domain).toDbName
      val tableComment  = escapeSingleQuotes(table.name)
      Seq(
        s"COMMENT ON TABLE $fullTableName IS '$tableComment';\n",
      ) ++
        table.fields.filter(_.name.nonEmpty).map { f =>
          val fieldName    = wrapQuotes(f.dbFieldName)
          val fieldComment = escapeSingleQuotes(f.name)
          s"COMMENT ON COLUMN $fullTableName.$fieldName IS '$fieldComment';\n"
        }
    }.mkString("\n", "\n", "")

  private def generateRelations(): String =
    domain.tables.values.flatMap { table =>
      val fullTableName = getFullTableName(table, domain).toDbName

      table.relations
        .filter(!_.logical)
        .map { relation =>
          val relationId   = wrapQuotes(getTableForeignKeyConstraintName(table.tableName, relation.id))
          val refTable     = domain.tables(relation.referenceTableId)
          val refTableName = getFullTableName(refTable, domain).toDbName
          val fields1      = relation.fields
            .map(f => getTableDbFieldName(table.fields, f._1))
            .mkString("(", ", ", ")")
          val fields2      = relation.fields
            .map(f => getTableDbFieldName(refTable.fields, f._2))
            .mkString("(", ", ", ")")
          val onDelete     = if (relation.onDelete != NoAction) s" ON DELETE ${relation.onDelete.sqlAction()}" else ""
          val onUpdate     = if (relation.onDelete != NoAction) s" ON UPDATE ${relation.onUpdate.sqlAction()}" else ""
          val createIndex  = if (relation.relationType == OneToOne) {
            val wrappedIndexId = wrapQuotes(getTableForeignKeyUniqueIndexConstraintName(table.tableName, relation.id))
            s"CREATE UNIQUE INDEX $wrappedIndexId ON $fullTableName$fields1;\n"
          } else ""
          s"ALTER TABLE $fullTableName ADD CONSTRAINT $relationId " +
            s"FOREIGN KEY $fields1 REFERENCES $refTableName $fields2" +
            s"$onDelete$onUpdate;\n$createIndex"
        }
    }.mkString("\n", "\n", "")

  private def getNameComment(name: String): Option[String] =
    if withNameComment && name.trim.nonEmpty then Some(s"-- ${name.trim}")
    else None

  private def getDescriptionComments(description: String): Seq[String] =
    if (withDescriptionComment && description.trim.nonEmpty) {
      description.trim.split("\n").map(s => s"-- $s").toSeq
    } else {
      Seq.empty
    }
}
