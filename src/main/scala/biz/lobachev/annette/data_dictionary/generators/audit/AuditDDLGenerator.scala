package biz.lobachev.annette.data_dictionary.generators.audit

import biz.lobachev.annette.data_dictionary.generators.{GeneratedFile, TextGenerator}
import biz.lobachev.annette.data_dictionary.labels.Audit.{AUDIT_TABLE, DISABLE_AUDIT}
import biz.lobachev.annette.data_dictionary.model.*
import biz.lobachev.annette.data_dictionary.utils.StringSyntax.*

import java.time.OffsetDateTime
import java.time.format.DateTimeFormatter

case class AuditDDLGenerator(
  domain: Domain,
  filename: String = "audit_ddl.sql",
) extends TextGenerator
    with DomainMetaHelper {

  override def generate(): Seq[GeneratedFile] = {
    val audit       = generateAudit()
    val tableNames  = audit.map(_._1).toSet
    val auditTables = generateAuditTables(tableNames)

    auditTables.map { auditTable =>
      val content = header() + auditTable + audit.map(_._2).mkString("\n")

      GeneratedFile(
        s"",
        filename,
        content,
      )
    }.toSeq

  }

  private def header() = {
    val formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")
    val date      = OffsetDateTime.now().toLocalDateTime.format(formatter)
    Seq(
      s"-- ${domain.name}",
      "-- Code generated by Data Dictionary Builder (c) Valery Lobachev (https://github.com/valerylobachev/data-dictionary-builder).",
      s"-- Date: $date",
      "",
    ).mkString("\n")
  }

  private def generateAudit() =
    domain.tables.values.flatMap { table =>
      getTableLabel(table, AUDIT_TABLE, domain)
        .filter(_ => getTableLabel(table, DISABLE_AUDIT, domain).map(_ != "true").getOrElse(true))
        .map { auditTable =>
          val tableName       = getFullTableName(table, domain).toDbName
          val auditFunc       = table.tableName + "_audit_func"
          val trigger         = table.tableName + "_audit_trigger"
          val pkFields        = table.pk
            .map(pkField => getTableDbFieldName(table.fields, pkField))
          val newIdExpression = pkFields.map(f => s"NEW.$f::text").mkString(" || '|' || ")
          val oldIdExpression = pkFields.map(f => s"OLD.$f::text").mkString(" || '|' || ")

          val updatedByField = table.fields.find { f =>
            val datatype = getPostgresTableFieldDatatype(f, domain).documentationDatatype()

            f.fieldName == "updatedBy" && (
              datatype.startsWith("char") ||
                datatype.startsWith("varchar") ||
                datatype.startsWith("text")
            )
          }
            .map(f => getTableDbFieldName(table.fields, f.fieldName))

          val newUpdatedBy = updatedByField.map(f => s"NEW.$f").getOrElse("NULL")

          val audit =
            s"""CREATE OR REPLACE FUNCTION $auditFunc()
               |    RETURNS trigger AS
               |$$$$
               |BEGIN
               |    if (TG_OP = 'INSERT') then
               |        INSERT INTO $auditTable ("table",
               |                            id,
               |                            dt,
               |                            operation,
               |                            prev_data,
               |                            new_data,
               |                            updated_by)
               |        VALUES (TG_TABLE_NAME,
               |                $newIdExpression,
               |                CURRENT_TIMESTAMP,
               |                'I',
               |                null,
               |                to_jsonb(NEW),
               |                $newUpdatedBy);
               |        RETURN NEW;
               |    elsif (TG_OP = 'UPDATE') then
               |        INSERT INTO $auditTable ("table",
               |                            id,
               |                            dt,
               |                            operation,
               |                            prev_data,
               |                            new_data,
               |                            updated_by)
               |        VALUES (TG_TABLE_NAME,
               |                $newIdExpression,
               |                CURRENT_TIMESTAMP,
               |                'U',
               |                jsonb_diff_val(to_jsonb(OLD), to_jsonb(NEW)),
               |                jsonb_diff_val(to_jsonb(NEW), to_jsonb(OLD)),
               |                $newUpdatedBy);
               |        RETURN NEW;
               |    elsif (TG_OP = 'DELETE') then
               |        INSERT INTO $auditTable ("table",
               |                            id,
               |                            dt,
               |                            operation,
               |                            prev_data,
               |                            new_data,
               |                            updated_by)
               |        VALUES (TG_TABLE_NAME,
               |                $oldIdExpression,
               |                CURRENT_TIMESTAMP,
               |                'D',
               |                to_jsonb(OLD),
               |                NULL,
               |                NULL);
               |
               |        RETURN OLD;
               |    end if;
               |END;
               |$$$$ LANGUAGE plpgsql;
               |
               |CREATE OR REPLACE TRIGGER $trigger
               |    AFTER INSERT OR UPDATE OR DELETE
               |    ON $tableName
               |    FOR EACH ROW
               |EXECUTE FUNCTION $auditFunc(); """.stripMargin

          auditTable -> audit
        }
    }

  private def generateAuditTables(tableNames: Set[String]) =
    if (tableNames.nonEmpty) {
      val auditTables  = tableNames
        .map(t => s"""CREATE TABLE $t (
                     |  "table" text NOT NULL,
                     |  "id" text NOT NULL,
                     |  "counter" bigserial NOT NULL,
                     |  "dt" timestamptz NOT NULL,
                     |  "operation" varchar(1) NOT NULL,
                     |  "prev_data" jsonb,
                     |  "new_data" jsonb,
                     |  "updated_by" text,
                     |  PRIMARY KEY ("table", "id", "counter")
                     |);\n""".stripMargin)
        .toSeq
      val jsonDiffFunc =
        s"""CREATE OR REPLACE FUNCTION jsonb_diff_val(val1 JSONB, val2 JSONB)
           |    RETURNS JSONB AS
           |$$$$
           |DECLARE
           |    result JSONB;
           |    v      RECORD;
           |BEGIN
           |    result = val1;
           |    FOR v IN SELECT * FROM jsonb_each(val2)
           |        LOOP
           |            IF result @> jsonb_build_object(v.key, v.value)
           |            THEN
           |                result = result - v.key;
           |            ELSIF result ? v.key THEN
           |                CONTINUE;
           |            ELSE
           |                result = result || jsonb_build_object(v.key, 'null');
           |            END IF;
           |        END LOOP;
           |    RETURN result;
           |END;
           |$$$$ LANGUAGE plpgsql;\n\n""".stripMargin
      Some(
        (auditTables ++ Seq(jsonDiffFunc)).mkString("\n", "\n", ""),
      )
    } else None

}
